class ValidationFailure(RuntimeError):
    """Raised when model validation cannot be completed."""


@dataclass(frozen=True)
class ValidationIssue:
    """One validation warning or error."""

    severity: str
    check: str
    message: str


@dataclass
class ValidationReport:
    """Complete machine-readable validation outcome."""

    protocol: str = PROTOCOL_NAME
    validation_started_utc: str = ""
    validation_finished_utc: str = ""
    project_root: str = ""
    strict_mode: bool = False
    dataset_check_enabled: bool = True
    status: str = "RUNNING"
    model_id: str | None = None
    evidence_scope: str | None = None
    checks_passed: list[str] = field(default_factory=list)
    issues: list[ValidationIssue] = field(default_factory=list)
    artifact_details: dict[str, Any] = field(default_factory=dict)
    threshold_details: dict[str, Any] = field(default_factory=dict)
    inference_details: dict[str, Any] = field(default_factory=dict)
    metric_details: dict[str, Any] = field(default_factory=dict)
    runtime: dict[str, Any] = field(default_factory=dict)

    def add_pass(self, check: str) -> None:
        """Record a successful validation check once."""

        if check not in self.checks_passed:
            self.checks_passed.append(check)

    def add_warning(self, check: str, message: str) -> None:
        """Record a non-fatal validation warning."""

        self.issues.append(
            ValidationIssue(
                severity="WARNING",
                check=check,
                message=message,
            )
        )

    def add_error(self, check: str, message: str) -> None:
        """Record a fatal validation error."""

        self.issues.append(
            ValidationIssue(
                severity="ERROR",
                check=check,
                message=message,
            )
        )

    @property
    def errors(self) -> list[ValidationIssue]:
        return [
            issue
            for issue in self.issues
            if issue.severity == "ERROR"
        ]

    @property
    def warnings(self) -> list[ValidationIssue]:
        return [
            issue
            for issue in self.issues
            if issue.severity == "WARNING"
        ]

    def finalize(self) -> None:
        """Derive the final report status."""

        self.validation_finished_utc = utc_now_iso()

        if self.errors:
            self.status = "FAIL"
        elif self.strict_mode and self.warnings:
            self.status = "FAIL_STRICT"
        elif self.warnings:
            self.status = "PASS_WITH_WARNINGS"
        else:
            self.status = "PASS"

    def to_dictionary(self) -> dict[str, Any]:
        """Convert nested dataclasses to JSON-compatible data."""

        return asdict(self)


def utc_now_iso() -> str:
    """Return a stable timezone-aware UTC timestamp."""

    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def configure_logging() -> logging.Logger:
    """Configure console and persistent validation logging."""

    LOG_DIR.mkdir(parents=True, exist_ok=True)

    logger = logging.getLogger("ft_qupap.validate_model_files")
    logger.setLevel(logging.INFO)
    logger.handlers.clear()

    formatter = logging.Formatter(
        "%(asctime)s | %(levelname)s | %(message)s"
    )

    console_handler = logging.StreamHandler()
    console_handler.setFormatter(formatter)

    file_handler = logging.FileHandler(LOG_FILE, encoding="utf-8")
    file_handler.setFormatter(formatter)

    logger.addHandler(console_handler)
    logger.addHandler(file_handler)
    return logger


