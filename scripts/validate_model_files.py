#!/usr/bin/env python3
"""
Validate the exported FT-QuPAP Gaussian Process model bundle.

This script is the independent deployment gate for the artifacts created by
scripts/export_gp_model.py. It does not train, tune, recalibrate, or overwrite
the detector. It verifies that the Authentication Server can safely load and
use the model bundle required by flowchart Steps 17-19:

    Step 17: construct the nine observable GP features,
    Step 18: estimate calibrated P(attack),
    Step 19: apply accept / retry / reject thresholds.

Validated model bundle:
    models/gp_model.pkl
    models/feature_scaler.pkl
    models/calibration_model.pkl
    models/threshold.json
    models/feature_order.json
    models/model_metadata.json

Optional cross-check inputs:
    data/processed/independent_test_features.csv
    data/results/performance_metrics.csv
    data/results/confusion_matrix.csv

Main checks:
    1. Required files exist and are non-empty.
    2. JSON files are valid and mutually consistent.
    3. Model-file SHA-256 hashes match model_metadata.json.
    4. Exported feature order exactly matches the notebook schema.
    5. StandardScaler, GaussianProcessClassifier, and IsotonicRegression
       objects have compatible dimensions and fitted attributes.
    6. Thresholds obey the FT-QuPAP accept/retry/reject policy.
    7. A single-row and batch inference smoke test produce finite P(attack)
       values in [0, 1].
    8. The isotonic calibrator is monotonic.
    9. When the held-out test split exists, metrics and confusion counts are
       independently recomputed and compared with exported result files.
   10. The model ID is recomputed from the artifact hashes and policy data.

Security note:
    joblib/pickle files can execute code while loading. Validate only model
    files generated by this project or obtained from a fully trusted source.

Run from the project root:
    python scripts/validate_model_files.py

Useful options:
    python scripts/validate_model_files.py --strict
    python scripts/validate_model_files.py --sample-rows 128
    python scripts/validate_model_files.py --skip-dataset-check
    python scripts/validate_model_files.py --report outputs/reports/model_validation_report.json
"""

