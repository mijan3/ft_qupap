def _evidence_scope_from_sources(
    model_metadata: Mapping[str, Any],
    artifacts: Sequence[ArtifactStatus],
) -> str:
    for key in (
        "evidence_scope",
        "research_scope",
        "source_research_scope",
    ):
        if model_metadata.get(key) is not None:
            return str(model_metadata[key])

    scopes = {
        artifact.evidence_scope
        for artifact in artifacts
        if artifact.exists
        and artifact.evidence_scope
        not in {"unspecified", "unavailable"}
    }

    if len(scopes) == 1:
        return next(iter(scopes))

    if len(scopes) > 1:
        return "mixed"

    return "unspecified"


def load_prediction_evidence() -> PredictionEvidence | None:
    """Load the first chart-ready label/probability table."""

    for path in PREDICTION_SOURCES:
        rows = _safe_read_csv_rows(path)

        if not rows:
            continue

        columns = rows[0].keys()
        label_column = first_existing_column(
            columns,
            LABEL_COLUMNS,
        )
        probability_column = first_existing_column(
            columns,
            PROBABILITY_COLUMNS,
        )

        if label_column is None or probability_column is None:
            continue

        usable = []

        for row in rows:
            if (
                row.get(label_column) is None
                or row.get(probability_column) is None
            ):
                continue

            probability = _finite_float(
                row.get(probability_column)
            )

            if probability is None or not 0.0 <= probability <= 1.0:
                continue

            record = dict(row)
            record[probability_column] = probability
            usable.append(record)

        if len(usable) < 2:
            continue

        labels = {
            str(row[label_column]).strip().lower()
            for row in usable
        }

        # The chart builders perform complete validation; here we only avoid
        # selecting an obvious one-class table.
        attack_tokens = {"1", "true", "attack", "malicious", "attacker"}
        benign_tokens = {"0", "false", "benign", "normal", "valid"}

        has_attack = bool(labels & attack_tokens)
        has_benign = bool(labels & benign_tokens)

        if not (has_attack and has_benign):
            continue

        scope = _artifact_scope(path)

        return PredictionEvidence(
            source=str(path.relative_to(PROJECT_ROOT)),
            row_count=len(usable),
            label_column=label_column,
            probability_column=probability_column,
            evidence_scope=scope,
            rows=tuple(usable),
        )

    return None


