def _load_table(path: Path) -> Any | None:
    """Load a dataframe for visual exploration."""

    if not path.is_file():
        return None

    try:
        pd = _pandas()
        table = pd.read_csv(path)
    except Exception:
        return None

    if table.empty:
        return None

    # Redact column values through record conversion.
    safe_rows = sanitize_mapping(
        table.to_dict(orient="records")
    )

    if not isinstance(safe_rows, list):
        return None

    return pd.DataFrame(safe_rows)


