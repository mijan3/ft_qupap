def _metric_status(
    metric_name: str,
    value: Any,
) -> str:
    """Apply conservative visual semantics without making research claims."""

    number = _finite_float(value)

    if number is None:
        return "inactive"

    if metric_name in {
        "held_out_roc_auc",
        "held_out_pr_auc",
        "independent_roc_auc",
        "independent_pr_auc",
        "attack_detection_rate",
        "valid_user_acceptance_rate",
        "tag_recovery_success_rate",
    }:
        if number >= 0.90:
            return "verified"
        if number >= 0.75:
            return "warning"
        return "failed"

    if metric_name in {
        "held_out_brier_score",
        "held_out_ece",
        "attack_acceptance_rate",
        "false_reject_rate",
    }:
        if number <= 0.05:
            return "verified"
        if number <= 0.15:
            return "warning"
        return "failed"

    return "ready"


def _format_metric(metric_name: str, value: Any) -> str:
    presentation = METRIC_PRESENTATION.get(metric_name)

    if presentation is None:
        return format_value(value)

    _, kind, _ = presentation

    if kind == "percentage":
        return format_percentage(value)

    if kind == "probability":
        return format_probability(value)

    if kind == "duration":
        return format_duration(value)

    if kind == "integer":
        number = _optional_int(value)
        return f"{number:,}" if number is not None else "—"

    return format_value(value)


def _metric_items(
    snapshot: ResultsSnapshot,
) -> tuple[MetricItem, ...]:
    items = []

    for name in METRIC_PRESENTATION:
        if name not in snapshot.metric_values:
            continue

        label, _, help_text = METRIC_PRESENTATION[name]
        value = snapshot.metric_values[name]

        items.append(
            MetricItem(
                label=label,
                value=_format_metric(name, value),
                help_text=help_text,
                status=_metric_status(name, value),
            )
        )

    return tuple(items)


