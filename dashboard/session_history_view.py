"""
Research-results page for the FT-QuPAP Streamlit dashboard.

The page presents only stored and traceable evidence generated by the
FT-QuPAP notebook or approved project scripts. It organizes results into the
same categories required by the protocol-and-results storage report:

- correctness and valid-user availability
- security detection and false acceptance
- Gaussian Process discrimination and calibration
- quantum-channel and Steane CSS behavior
- retry-policy outcomes
- baseline comparison
- protocol runtime and resource cost
- representative Qiskit/Aer validation
- reproducibility metadata and artifact inventory

No numerical result is embedded as a fallback. A metric appears only when a
managed CSV/JSON artifact contains that value. Missing evidence is rendered
as unavailable.

Research boundary
-----------------
Full protocol sessions are syndrome-level simulations. Qiskit/Aer results are
representative encoded-block validation. GP output is a calibrated attack
probability under the evaluated data distribution, not proof of
eavesdropping. Development/demo evidence is labeled and must not be silently
presented as final paper evidence.

Security boundary
-----------------
Result tables are passed through the dashboard redaction layer. Private keys,
shared secrets, K_auth, K_ctrl, K_ss, raw subscriber identities, ciphertexts,
signatures, and raw authentication tags are never displayed or exported.
"""

