def _prediction_arrays(
    evidence: PredictionEvidence,
) -> tuple[list[Any], list[float]]:
    labels = [
        row[evidence.label_column]
        for row in evidence.rows
    ]
    probabilities = [
        float(row[evidence.probability_column])
        for row in evidence.rows
    ]
    return labels, probabilities


