def _validate_hex_digest(
    value: str,
    *,
    field_name: str,
) -> str:
    """Validate a 32-byte hexadecimal digest."""

    validated = validate_non_empty_string(
        value,
        field_name=field_name,
        minimum_length=64,
        maximum_length=64,
    ).lower()

    try:
        bytes.fromhex(
            validated
        )

    except ValueError as exc:
        raise ProtocolValidationError(
            f"{field_name} must be hexadecimal text."
        ) from exc

    return validated


def normalize_server_nonce(
    nonce: bytes | str,
) -> bytes:
    """
    Normalize a fresh Authentication Server nonce.

    Accepted representations:

    - Raw bytes
    - Hexadecimal string
    """

    if isinstance(
        nonce,
        bytes,
    ):
        return validate_bytes(
            nonce,
            field_name="server_nonce",
            minimum_length=16,
            maximum_length=64,
        )

    if not isinstance(
        nonce,
        str,
    ):
        raise ProtocolValidationError(
            (
                "server_nonce must be raw bytes or "
                "hexadecimal text."
            )
        )

    normalized_text = validate_non_empty_string(
        nonce,
        field_name="server_nonce",
        minimum_length=32,
        maximum_length=128,
    ).strip()

    if len(normalized_text) % 2 != 0:
        raise ProtocolValidationError(
            "Hexadecimal server_nonce must have an even length."
        )

    try:
        nonce_bytes = bytes.fromhex(
            normalized_text
        )

    except ValueError as exc:
        raise ProtocolValidationError(
            "server_nonce contains invalid hexadecimal text."
        ) from exc

    return validate_bytes(
        nonce_bytes,
        field_name="server_nonce",
        minimum_length=16,
        maximum_length=64,
    )


def normalize_transcript_binding(
    transcript_binding: bytes | str | None,
) -> str | None:
    """
    Normalize an optional transcript digest.

    The result is hexadecimal SHA3-256 text.
    """

    if transcript_binding is None:
        return None

    if isinstance(
        transcript_binding,
        bytes,
    ):
        validated = validate_bytes(
            transcript_binding,
            field_name="transcript_binding",
            exact_length=32,
        )

        return validated.hex()

    return _validate_hex_digest(
        transcript_binding,
        field_name="transcript_binding",
    )


def validate_mlkem_public_package(
    package: Mapping[str, Any],
    *,
    session_id: str,
    attempt_number: int,
) -> dict[str, Any]:
    """
    Validate the public ML-KEM package generated for this attempt.
    """

    if not isinstance(
        package,
        Mapping,
    ):
        raise ProtocolValidationError(
            "mlkem_public_package must be a mapping."
        )

    required_fields = (
        "session_id",
        "attempt_number",
        "algorithm",
        "key_id",
        "public_key_fingerprint",
        "public_key",
        "created_at",
        "expires_at",
    )

    missing_fields = [
        field_name
        for field_name in required_fields
        if field_name not in package
    ]

    if missing_fields:
        raise ProtocolValidationError(
            "ML-KEM public package is incomplete.",
            details={
                "missing_fields": missing_fields,
            },
        )

    normalized = dict(
        package
    )

    if normalized["session_id"] != session_id:
        raise ProtocolValidationError(
            (
                "ML-KEM public package session ID "
                "does not match the server package."
            )
        )

    if normalized["attempt_number"] != attempt_number:
        raise ProtocolValidationError(
            (
                "ML-KEM public package attempt number "
                "does not match the server package."
            )
        )

    validate_non_empty_string(
        normalized["algorithm"],
        field_name="mlkem_algorithm",
        minimum_length=1,
        maximum_length=64,
    )

    validate_non_empty_string(
        normalized["key_id"],
        field_name="mlkem_key_id",
        minimum_length=8,
        maximum_length=128,
    )

    _validate_hex_digest(
        normalized[
            "public_key_fingerprint"
        ],
        field_name=(
            "mlkem_public_key_fingerprint"
        ),
    )

    validate_non_empty_string(
        normalized["public_key"],
        field_name="mlkem_public_key",
        minimum_length=16,
        maximum_length=200_000,
    )

    created_at = validate_integer(
        normalized["created_at"],
        field_name="mlkem_created_at",
        minimum=0,
    )

    expires_at = validate_integer(
        normalized["expires_at"],
        field_name="mlkem_expires_at",
        minimum=0,
    )

    if expires_at <= created_at:
        raise ProtocolValidationError(
            (
                "ML-KEM public-key expiration must "
                "be later than its creation timestamp."
            )
        )

    return normalized


def validate_control_schedule_envelope(
    envelope: Mapping[str, Any],
) -> dict[str, Any]:
    """
    Validate the encrypted control-schedule envelope.

    The precise envelope fields are produced by the corresponding
    control-schedule encryption component. This function requires the
    authenticated-encryption fields needed by the receiver.
    """

    if not isinstance(
        envelope,
        Mapping,
    ):
        raise ProtocolValidationError(
            (
                "encrypted_control_schedule must "
                "be a mapping."
            )
        )

    required_fields = (
        "algorithm",
        "nonce",
        "ciphertext",
    )

    missing_fields = [
        field_name
        for field_name in required_fields
        if field_name not in envelope
    ]

    if missing_fields:
        raise ProtocolValidationError(
            (
                "Encrypted control-schedule "
                "envelope is incomplete."
            ),
            details={
                "missing_fields": missing_fields,
            },
        )

    normalized = dict(
        envelope
    )

    validate_non_empty_string(
        normalized["algorithm"],
        field_name=(
            "control_schedule_algorithm"
        ),
        minimum_length=1,
        maximum_length=64,
    )

    validate_non_empty_string(
        normalized["nonce"],
        field_name=(
            "control_schedule_nonce"
        ),
        minimum_length=8,
        maximum_length=10_000,
    )

    validate_non_empty_string(
        normalized["ciphertext"],
        field_name=(
            "control_schedule_ciphertext"
        ),
        minimum_length=8,
        maximum_length=10_000_000,
    )

    if "tag" in normalized:
        validate_non_empty_string(
            normalized["tag"],
            field_name="control_schedule_tag",
            minimum_length=8,
            maximum_length=10_000,
        )

    return normalized


