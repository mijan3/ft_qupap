def run_server_package_signer_self_test() -> dict[str, Any]:
    """
    Test M2 construction, signing, verification, tamper detection,
    and expiration rejection.
    """

    try:
        with TemporaryDirectory() as directory:
            root = Path(
                directory
            )

            key_manager = MLDSAKeyManager(
                public_key_path=(
                    root / "mldsa-public.json"
                ),
                secret_key_path=(
                    root / "mldsa-secret.json"
                ),
            )

            key_manager.generate_keypair()

            session_id = (
                "FTQ-SERVER-PACKAGE-SELF-TEST"
            )

            attempt_number = 1

            mlkem_public_package = {
                "session_id": session_id,
                "attempt_number": (
                    attempt_number
                ),
                "algorithm": "ML-KEM-768",
                "key_id": (
                    "MLKEM-SELF-TEST-KEY-00000001"
                ),
                "public_key_fingerprint": (
                    hashlib.sha3_256(
                        b"P" * 64
                    ).hexdigest()
                ),
                "public_key": encode_base64(
                    b"P" * 64
                ),
                "created_at": 1_700_000_000,
                "expires_at": 1_700_000_120,
            }

            encrypted_control_schedule = {
                "version": (
                    "FT-QuPAP-Control-Schedule-v1"
                ),
                "algorithm": "AES-256-GCM",
                "nonce": encode_base64(
                    b"N" * 12
                ),
                "ciphertext": encode_base64(
                    b"C" * 128
                ),
                "tag": encode_base64(
                    b"T" * 16
                ),
            }

            signed_result = sign_server_package(
                session_id=session_id,
                attempt_number=attempt_number,
                pseudonym_id=(
                    "PID-FTQ-SERVER-PACKAGE-001"
                ),
                server_nonce=(
                    b"S" * 32
                ),
                mlkem_public_package=(
                    mlkem_public_package
                ),
                encrypted_control_schedule=(
                    encrypted_control_schedule
                ),
                key_manager=key_manager,
                issued_at=1_700_000_000,
                ttl_seconds=120,
                transcript_binding=(
                    b"H" * 32
                ),
                metadata={
                    "context": "urban",
                },
            )

            network_package = (
                signed_result.to_dict()
            )

            verification_result = (
                verify_signed_server_package(
                    network_package,
                    key_manager=key_manager,
                    checked_at=1_700_000_050,
                )
            )

            tampered_package = dict(
                network_package
            )

            tampered_package[
                "attempt_number"
            ] = 2

            tampered_result = (
                verify_signed_server_package(
                    tampered_package,
                    key_manager=key_manager,
                    checked_at=1_700_000_050,
                )
            )

            expired_result = (
                verify_signed_server_package(
                    network_package,
                    key_manager=key_manager,
                    checked_at=1_700_000_121,
                )
            )

            secret_fields_absent = all(
                field_name
                not in network_package
                for field_name in (
                    "secret_key",
                    "mlkem_secret_key",
                    "mldsa_secret_key",
                )
            )

            success = all(
                (
                    verification_result.valid,
                    verification_result
                    .signature_valid,
                    verification_result
                    .fingerprint_valid,
                    verification_result
                    .validity_period_valid,

                    not tampered_result.valid,

                    (
                        not tampered_result
                        .signature_valid
                        or not tampered_result
                        .fingerprint_valid
                        or not tampered_result
                        .structure_valid
                    ),

                    not expired_result.valid,

                    not expired_result
                    .validity_period_valid,

                    secret_fields_absent,
                )
            )

            return {
                "success": success,

                "package_version": (
                    network_package[
                        "version"
                    ]
                ),

                "message_type": (
                    network_package[
                        "message_type"
                    ]
                ),

                "session_id": (
                    network_package[
                        "session_id"
                    ]
                ),

                "attempt_number": (
                    network_package[
                        "attempt_number"
                    ]
                ),

                "package_fingerprint": (
                    signed_result
                    .package_fingerprint
                ),

                "signature_bytes": len(
                    signed_result.signature
                ),

                "valid_package_accepted": (
                    verification_result.valid
                ),

                "valid_signature": (
                    verification_result
                    .signature_valid
                ),

                "tampered_package_rejected": (
                    not tampered_result.valid
                ),

                "expired_package_rejected": (
                    not expired_result.valid
                ),

                "secret_fields_absent": (
                    secret_fields_absent
                ),
            }

    except Exception as exc:
        return {
            "success": False,
            "error": str(exc),
            "error_type": type(
                exc
            ).__name__,
        }


