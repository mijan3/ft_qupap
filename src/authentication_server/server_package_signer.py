class ServerPackageSigningError(RuntimeError):
    """Raised when an M2 server package cannot be created or verified."""

    def __init__(
        self,
        message: str,
        *,
        details: Mapping[str, Any] | None = None,
    ) -> None:
        super().__init__(message)

        self.details = (
            {}
            if details is None
            else dict(details)
        )


