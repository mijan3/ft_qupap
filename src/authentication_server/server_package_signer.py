@dataclass(frozen=True)
class SignedServerPackage:
    """
    Complete signed FT-QuPAP M2 server package.

    Attributes
    ----------
    unsigned_package:
        Canonical package fields covered by the ML-DSA signature.

    signature:
        ML-DSA signature generated by the Authentication Server.

    package_fingerprint:
        SHA3-256 fingerprint of the canonical unsigned package.

    signing_key_id:
        Identifier of the server ML-DSA key used for signing.
    """

    unsigned_package: dict[str, Any]

    signature: bytes

    package_fingerprint: str

    signing_key_id: str
    signing_algorithm: str

    issued_at: int
    expires_at: int

    def __post_init__(self) -> None:
        if not isinstance(
            self.unsigned_package,
            dict,
        ):
            raise ProtocolValidationError(
                "unsigned_package must be a dictionary."
            )

        validate_bytes(
            self.signature,
            field_name="mldsa_signature",
            minimum_length=32,
            maximum_length=100_000,
        )

        _validate_hex_digest(
            self.package_fingerprint,
            field_name="package_fingerprint",
        )

        validate_non_empty_string(
            self.signing_key_id,
            field_name="signing_key_id",
            minimum_length=8,
            maximum_length=128,
        )

        validate_non_empty_string(
            self.signing_algorithm,
            field_name="signing_algorithm",
            minimum_length=1,
            maximum_length=64,
        )

        validate_integer(
            self.issued_at,
            field_name="issued_at",
            minimum=0,
        )

        validate_integer(
            self.expires_at,
            field_name="expires_at",
            minimum=0,
        )

        if self.expires_at <= self.issued_at:
            raise ProtocolValidationError(
                (
                    "Server-package expiration must be "
                    "later than its issue timestamp."
                )
            )

        expected_fingerprint = (
            calculate_server_package_fingerprint(
                self.unsigned_package
            )
        )

        if not hmac.compare_digest(
            self.package_fingerprint.lower(),
            expected_fingerprint,
        ):
            raise ProtocolValidationError(
                (
                    "Server-package fingerprint does not "
                    "match the unsigned package."
                )
            )

        package_issued_at = self.unsigned_package.get(
            "issued_at"
        )

        package_expires_at = self.unsigned_package.get(
            "expires_at"
        )

        if (
            package_issued_at != self.issued_at
            or package_expires_at != self.expires_at
        ):
            raise ProtocolValidationError(
                (
                    "Result timestamps do not match the "
                    "unsigned package timestamps."
                )
            )

    def to_dict(self) -> dict[str, Any]:
        """
        Return the complete network-safe signed package.
        """

        result = dict(
            self.unsigned_package
        )

        result.update(
            {
                "package_fingerprint": (
                    self.package_fingerprint
                ),
                "signature": encode_base64(
                    self.signature
                ),
            }
        )

        return result

    def __repr__(self) -> str:
        return (
            "SignedServerPackage("
            f"message_type="
            f"{self.unsigned_package.get('message_type')!r}, "
            f"session_id="
            f"{self.unsigned_package.get('session_id')!r}, "
            f"attempt_number="
            f"{self.unsigned_package.get('attempt_number')!r}, "
            f"signing_key_id={self.signing_key_id!r}, "
            f"signing_algorithm={self.signing_algorithm!r}, "
            f"package_fingerprint="
            f"{self.package_fingerprint!r}, "
            f"issued_at={self.issued_at}, "
            f"expires_at={self.expires_at}, "
            "signature=<hidden>"
            ")"
        )


@dataclass(frozen=True)
class ServerPackageVerificationResult:
    """
    Result of signed M2 server-package verification.
    """

    valid: bool

    signature_valid: bool
    fingerprint_valid: bool
    validity_period_valid: bool
    structure_valid: bool

    session_id: str | None
    attempt_number: int | None

    signing_key_id: str | None
    package_fingerprint: str | None

    checked_at: int

    message: str

    details: dict[str, Any]

    def __post_init__(self) -> None:
        for field_name in (
            "valid",
            "signature_valid",
            "fingerprint_valid",
            "validity_period_valid",
            "structure_valid",
        ):
            if not isinstance(
                getattr(
                    self,
                    field_name,
                ),
                bool,
            ):
                raise ProtocolValidationError(
                    f"{field_name} must be Boolean."
                )

        expected_valid = all(
            (
                self.signature_valid,
                self.fingerprint_valid,
                self.validity_period_valid,
                self.structure_valid,
            )
        )

        if self.valid != expected_valid:
            raise ProtocolValidationError(
                (
                    "Server-package valid flag does not "
                    "match its individual checks."
                )
            )

        if self.session_id is not None:
            validate_non_empty_string(
                self.session_id,
                field_name="session_id",
                minimum_length=3,
                maximum_length=256,
            )

        if self.attempt_number is not None:
            validate_integer(
                self.attempt_number,
                field_name="attempt_number",
                minimum=1,
                maximum=100,
            )

        if self.signing_key_id is not None:
            validate_non_empty_string(
                self.signing_key_id,
                field_name="signing_key_id",
                minimum_length=8,
                maximum_length=128,
            )

        if self.package_fingerprint is not None:
            _validate_hex_digest(
                self.package_fingerprint,
                field_name="package_fingerprint",
            )

        validate_integer(
            self.checked_at,
            field_name="checked_at",
            minimum=0,
        )

        if not isinstance(
            self.message,
            str,
        ):
            raise ProtocolValidationError(
                "Verification message must be a string."
            )

        if not isinstance(
            self.details,
            dict,
        ):
            raise ProtocolValidationError(
                "Verification details must be a dictionary."
            )

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-compatible verification result."""

        return {
            "valid": self.valid,
            "signature_valid": self.signature_valid,
            "fingerprint_valid": (
                self.fingerprint_valid
            ),
            "validity_period_valid": (
                self.validity_period_valid
            ),
            "structure_valid": self.structure_valid,
            "session_id": self.session_id,
            "attempt_number": self.attempt_number,
            "signing_key_id": self.signing_key_id,
            "package_fingerprint": (
                self.package_fingerprint
            ),
            "checked_at": self.checked_at,
            "message": self.message,
            "details": dict(
                self.details
            ),
        }


