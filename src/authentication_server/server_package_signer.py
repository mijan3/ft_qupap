def sign_server_package(
    *,
    session_id: str,
    attempt_number: int,
    pseudonym_id: str,
    server_nonce: bytes | str,
    mlkem_public_package: Mapping[str, Any],
    encrypted_control_schedule: Mapping[str, Any],
    key_manager: MLDSAKeyManager | None = None,
    issued_at: int | None = None,
    ttl_seconds: int = (
        DEFAULT_SERVER_PACKAGE_TTL_SECONDS
    ),
    transcript_binding: bytes | str | None = None,
    server_id: str = SERVER_ID,
    metadata: Mapping[str, Any] | None = None,
) -> SignedServerPackage:
    """
    Build and ML-DSA-sign an M2 server package.
    """

    selected_key_manager = (
        get_default_mldsa_key_manager()
        if key_manager is None
        else key_manager
    )

    if not isinstance(
        selected_key_manager,
        MLDSAKeyManager,
    ):
        raise ProtocolValidationError(
            (
                "key_manager must be an "
                "MLDSAKeyManager object."
            )
        )

    signing_information = (
        selected_key_manager
        .get_public_information()
    )

    unsigned_package = (
        build_unsigned_server_package(
            session_id=session_id,
            attempt_number=attempt_number,
            pseudonym_id=pseudonym_id,
            server_nonce=server_nonce,
            mlkem_public_package=(
                mlkem_public_package
            ),
            encrypted_control_schedule=(
                encrypted_control_schedule
            ),
            signing_key_information=(
                signing_information
            ),
            issued_at=issued_at,
            ttl_seconds=ttl_seconds,
            transcript_binding=(
                transcript_binding
            ),
            server_id=server_id,
            metadata=metadata,
        )
    )

    canonical_package = (
        canonical_json_bytes(
            unsigned_package
        )
    )

    try:
        signature = (
            selected_key_manager.sign(
                canonical_package,
                context=(
                    SERVER_PACKAGE_SIGNING_CONTEXT
                ),
            )
        )

    except Exception as exc:
        raise ServerPackageSigningError(
            (
                "Authentication Server ML-DSA "
                "package signing failed."
            ),
            details={
                "session_id": session_id,
                "attempt_number": (
                    attempt_number
                ),
                "reason": str(exc),
            },
        ) from exc

    package_fingerprint = (
        calculate_server_package_fingerprint(
            unsigned_package
        )
    )

    return SignedServerPackage(
        unsigned_package=unsigned_package,
        signature=signature,
        package_fingerprint=(
            package_fingerprint
        ),
        signing_key_id=(
            signing_information[
                "key_id"
            ]
        ),
        signing_algorithm=(
            signing_information[
                "algorithm"
            ]
        ),
        issued_at=(
            unsigned_package[
                "issued_at"
            ]
        ),
        expires_at=(
            unsigned_package[
                "expires_at"
            ]
        ),
    )


