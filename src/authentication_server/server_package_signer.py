def build_unsigned_server_package(
    *,
    session_id: str,
    attempt_number: int,
    pseudonym_id: str,
    server_nonce: bytes | str,
    mlkem_public_package: Mapping[str, Any],
    encrypted_control_schedule: Mapping[str, Any],
    signing_key_information: Mapping[str, Any],
    issued_at: int | None = None,
    ttl_seconds: int = (
        DEFAULT_SERVER_PACKAGE_TTL_SECONDS
    ),
    transcript_binding: bytes | str | None = None,
    server_id: str = SERVER_ID,
    metadata: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """
    Build the canonical unsigned M2 server package.
    """

    validated_session_id = (
        validate_non_empty_string(
            session_id,
            field_name="session_id",
            minimum_length=3,
            maximum_length=256,
        )
    )

    validated_attempt = validate_integer(
        attempt_number,
        field_name="attempt_number",
        minimum=1,
        maximum=100,
    )

    validated_pseudonym = (
        validate_pseudonym_id(
            pseudonym_id
        )
    )

    validated_server_id = (
        validate_non_empty_string(
            server_id,
            field_name="server_id",
            minimum_length=1,
            maximum_length=256,
        )
    )

    normalized_nonce = normalize_server_nonce(
        server_nonce
    )

    selected_issued_at = (
        current_timestamp()
        if issued_at is None
        else validate_integer(
            issued_at,
            field_name="issued_at",
            minimum=0,
        )
    )

    validated_ttl = validate_integer(
        ttl_seconds,
        field_name="ttl_seconds",
        minimum=(
            MINIMUM_SERVER_PACKAGE_TTL_SECONDS
        ),
        maximum=(
            MAXIMUM_SERVER_PACKAGE_TTL_SECONDS
        ),
    )

    expires_at = (
        selected_issued_at
        + validated_ttl
    )

    normalized_mlkem_package = (
        validate_mlkem_public_package(
            mlkem_public_package,
            session_id=validated_session_id,
            attempt_number=validated_attempt,
        )
    )

    normalized_schedule = (
        validate_control_schedule_envelope(
            encrypted_control_schedule
        )
    )

    if not isinstance(
        signing_key_information,
        Mapping,
    ):
        raise ProtocolValidationError(
            (
                "signing_key_information must "
                "be a mapping."
            )
        )

    required_signing_fields = (
        "algorithm",
        "key_id",
        "fingerprint",
    )

    missing_signing_fields = [
        field_name
        for field_name
        in required_signing_fields
        if field_name
        not in signing_key_information
    ]

    if missing_signing_fields:
        raise ProtocolValidationError(
            (
                "ML-DSA signing-key information "
                "is incomplete."
            ),
            details={
                "missing_fields": (
                    missing_signing_fields
                ),
            },
        )

    signing_algorithm = (
        validate_non_empty_string(
            signing_key_information[
                "algorithm"
            ],
            field_name="mldsa_algorithm",
            minimum_length=1,
            maximum_length=64,
        )
    )

    signing_key_id = (
        validate_non_empty_string(
            signing_key_information[
                "key_id"
            ],
            field_name="mldsa_key_id",
            minimum_length=8,
            maximum_length=128,
        )
    )

    signing_fingerprint = (
        _validate_hex_digest(
            signing_key_information[
                "fingerprint"
            ],
            field_name=(
                "mldsa_public_key_fingerprint"
            ),
        )
    )

    normalized_transcript_binding = (
        normalize_transcript_binding(
            transcript_binding
        )
    )

    normalized_metadata = (
        {}
        if metadata is None
        else dict(metadata)
    )

    package: dict[str, Any] = {
        "version": SERVER_PACKAGE_VERSION,

        "protocol_domain": (
            PROTOCOL_DOMAIN_LABEL.decode(
                "utf-8",
                errors="strict",
            )
        ),

        "message_type": (
            SERVER_PACKAGE_MESSAGE_TYPE
        ),

        "server_id": validated_server_id,

        "session_id": (
            validated_session_id
        ),

        "attempt_number": (
            validated_attempt
        ),

        "pseudonym_id": (
            validated_pseudonym
        ),

        "server_nonce": encode_base64(
            normalized_nonce
        ),

        "issued_at": selected_issued_at,
        "expires_at": expires_at,

        "mlkem_public_package": (
            normalized_mlkem_package
        ),

        "encrypted_control_schedule": (
            normalized_schedule
        ),

        "signing_key": {
            "algorithm": signing_algorithm,
            "key_id": signing_key_id,
            "fingerprint": (
                signing_fingerprint
            ),
        },

        "metadata": normalized_metadata,
    }

    if normalized_transcript_binding is not None:
        package["transcript_binding"] = (
            normalized_transcript_binding
        )

    return package


def calculate_server_package_fingerprint(
    unsigned_package: Mapping[str, Any],
) -> str:
    """
    Calculate the SHA3-256 canonical package fingerprint.
    """

    if not isinstance(
        unsigned_package,
        Mapping,
    ):
        raise ProtocolValidationError(
            "unsigned_package must be a mapping."
        )

    encoded_package = canonical_json_bytes(
        dict(
            unsigned_package
        )
    )

    return hashlib.sha3_256(
        encoded_package
    ).hexdigest()


