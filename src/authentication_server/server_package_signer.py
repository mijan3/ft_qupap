def extract_unsigned_server_package(
    signed_package: Mapping[str, Any],
) -> tuple[
    dict[str, Any],
    bytes,
    str,
]:
    """
    Separate the unsigned fields, signature, and fingerprint.
    """

    if not isinstance(
        signed_package,
        Mapping,
    ):
        raise ProtocolValidationError(
            "signed_package must be a mapping."
        )

    required_fields = (
        "signature",
        "package_fingerprint",
    )

    missing_fields = [
        field_name
        for field_name in required_fields
        if field_name not in signed_package
    ]

    if missing_fields:
        raise ProtocolValidationError(
            "Signed server package is incomplete.",
            details={
                "missing_fields": missing_fields,
            },
        )

    unsigned_package = dict(
        signed_package
    )

    encoded_signature = unsigned_package.pop(
        "signature"
    )

    package_fingerprint = unsigned_package.pop(
        "package_fingerprint"
    )

    try:
        signature = decode_base64(
            encoded_signature
        )

    except Exception as exc:
        raise ProtocolValidationError(
            (
                "Unable to decode the server-package "
                "ML-DSA signature."
            )
        ) from exc

    validate_bytes(
        signature,
        field_name="mldsa_signature",
        minimum_length=32,
        maximum_length=100_000,
    )

    normalized_fingerprint = (
        _validate_hex_digest(
            package_fingerprint,
            field_name=(
                "package_fingerprint"
            ),
        )
    )

    return (
        unsigned_package,
        signature,
        normalized_fingerprint,
    )


def verify_signed_server_package(
    signed_package: Mapping[str, Any],
    *,
    key_manager: MLDSAKeyManager | None = None,
    public_key: bytes | None = None,
    checked_at: int | None = None,
    future_tolerance_seconds: int = (
        DEFAULT_FUTURE_TOLERANCE_SECONDS
    ),
) -> ServerPackageVerificationResult:
    """
    Verify the structure, fingerprint, validity period, and signature.

    The Authentication Server may use this for self-checking. The Mobile
    Station can use the equivalent logic with the trusted ML-DSA public
    key.
    """

    selected_timestamp = (
        current_timestamp()
        if checked_at is None
        else validate_integer(
            checked_at,
            field_name="checked_at",
            minimum=0,
        )
    )

    validated_future_tolerance = (
        validate_integer(
            future_tolerance_seconds,
            field_name=(
                "future_tolerance_seconds"
            ),
            minimum=0,
            maximum=3600,
        )
    )

    selected_key_manager = (
        get_default_mldsa_key_manager()
        if key_manager is None
        else key_manager
    )

    structure_valid = False
    fingerprint_valid = False
    validity_period_valid = False
    signature_valid = False

    session_id: str | None = None
    attempt_number: int | None = None
    signing_key_id: str | None = None
    package_fingerprint: str | None = None

    details: dict[str, Any] = {}

    try:
        (
            unsigned_package,
            signature,
            package_fingerprint,
        ) = extract_unsigned_server_package(
            signed_package
        )

        required_unsigned_fields = (
            "version",
            "protocol_domain",
            "message_type",
            "server_id",
            "session_id",
            "attempt_number",
            "pseudonym_id",
            "server_nonce",
            "issued_at",
            "expires_at",
            "mlkem_public_package",
            "encrypted_control_schedule",
            "signing_key",
        )

        missing_unsigned_fields = [
            field_name
            for field_name
            in required_unsigned_fields
            if field_name
            not in unsigned_package
        ]

        if missing_unsigned_fields:
            raise ProtocolValidationError(
                (
                    "Unsigned server package is "
                    "missing required fields."
                ),
                details={
                    "missing_fields": (
                        missing_unsigned_fields
                    ),
                },
            )

        if (
            unsigned_package["version"]
            != SERVER_PACKAGE_VERSION
        ):
            raise ProtocolValidationError(
                (
                    "Unsupported server-package "
                    "version."
                )
            )

        if (
            unsigned_package[
                "message_type"
            ]
            != SERVER_PACKAGE_MESSAGE_TYPE
        ):
            raise ProtocolValidationError(
                (
                    "Invalid server-package "
                    "message type."
                )
            )

        expected_domain = (
            PROTOCOL_DOMAIN_LABEL.decode(
                "utf-8",
                errors="strict",
            )
        )

        if (
            unsigned_package[
                "protocol_domain"
            ]
            != expected_domain
        ):
            raise ProtocolValidationError(
                (
                    "Server-package protocol "
                    "domain mismatch."
                )
            )

        session_id = (
            validate_non_empty_string(
                unsigned_package[
                    "session_id"
                ],
                field_name="session_id",
                minimum_length=3,
                maximum_length=256,
            )
        )

        attempt_number = (
            validate_integer(
                unsigned_package[
                    "attempt_number"
                ],
                field_name="attempt_number",
                minimum=1,
                maximum=100,
            )
        )

        validate_pseudonym_id(
            unsigned_package[
                "pseudonym_id"
            ]
        )

        normalize_server_nonce(
            decode_base64(
                unsigned_package[
                    "server_nonce"
                ]
            )
        )

        validate_mlkem_public_package(
            unsigned_package[
                "mlkem_public_package"
            ],
            session_id=session_id,
            attempt_number=attempt_number,
        )

        validate_control_schedule_envelope(
            unsigned_package[
                "encrypted_control_schedule"
            ]
        )

        signing_information = (
            unsigned_package[
                "signing_key"
            ]
        )

        if not isinstance(
            signing_information,
            Mapping,
        ):
            raise ProtocolValidationError(
                (
                    "signing_key must be "
                    "a mapping."
                )
            )

        signing_key_id = (
            validate_non_empty_string(
                signing_information[
                    "key_id"
                ],
                field_name="signing_key_id",
                minimum_length=8,
                maximum_length=128,
            )
        )

        issued_at = validate_integer(
            unsigned_package[
                "issued_at"
            ],
            field_name="issued_at",
            minimum=0,
        )

        expires_at = validate_integer(
            unsigned_package[
                "expires_at"
            ],
            field_name="expires_at",
            minimum=0,
        )

        if expires_at <= issued_at:
            raise ProtocolValidationError(
                (
                    "Server-package validity "
                    "period is invalid."
                )
            )

        structure_valid = True

        calculated_fingerprint = (
            calculate_server_package_fingerprint(
                unsigned_package
            )
        )

        fingerprint_valid = (
            hmac.compare_digest(
                calculated_fingerprint,
                package_fingerprint,
            )
        )

        validity_period_valid = (
            selected_timestamp
            >= (
                issued_at
                - validated_future_tolerance
            )
            and selected_timestamp
            <= expires_at
        )

        canonical_package = (
            canonical_json_bytes(
                unsigned_package
            )
        )

        signature_valid = (
            selected_key_manager.verify(
                canonical_package,
                signature,
                public_key=public_key,
                context=(
                    SERVER_PACKAGE_SIGNING_CONTEXT
                ),
            )
        )

        details.update(
            {
                "issued_at": issued_at,
                "expires_at": expires_at,
                "calculated_fingerprint": (
                    calculated_fingerprint
                ),
            }
        )

    except Exception as exc:
        details["error"] = str(
            exc
        )

        details["error_type"] = type(
            exc
        ).__name__

    valid = all(
        (
            structure_valid,
            fingerprint_valid,
            validity_period_valid,
            signature_valid,
        )
    )

    if valid:
        message = (
            "The signed FT-QuPAP server package "
            "is valid."
        )

    elif not structure_valid:
        message = (
            "The FT-QuPAP server-package "
            "structure is invalid."
        )

    elif not fingerprint_valid:
        message = (
            "The FT-QuPAP server-package "
            "fingerprint is invalid."
        )

    elif not validity_period_valid:
        message = (
            "The FT-QuPAP server package is "
            "expired or not yet valid."
        )

    else:
        message = (
            "The FT-QuPAP server-package "
            "ML-DSA signature is invalid."
        )

    return ServerPackageVerificationResult(
        valid=valid,
        signature_valid=signature_valid,
        fingerprint_valid=(
            fingerprint_valid
        ),
        validity_period_valid=(
            validity_period_valid
        ),
        structure_valid=structure_valid,
        session_id=session_id,
        attempt_number=attempt_number,
        signing_key_id=signing_key_id,
        package_fingerprint=(
            package_fingerprint
        ),
        checked_at=selected_timestamp,
        message=message,
        details=details,
    )


def require_valid_server_package(
    signed_package: Mapping[str, Any],
    *,
    key_manager: MLDSAKeyManager | None = None,
    public_key: bytes | None = None,
    checked_at: int | None = None,
) -> ServerPackageVerificationResult:
    """
    Verify a signed server package and raise when invalid.
    """

    result = verify_signed_server_package(
        signed_package,
        key_manager=key_manager,
        public_key=public_key,
        checked_at=checked_at,
    )

    if not result.valid:
        raise ServerPackageSigningError(
            result.message,
            details=result.to_dict(),
        )

    return result


