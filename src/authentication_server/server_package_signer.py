"""
Signed M2 server-package construction for FT-QuPAP v5.1.

After receiving and validating the Mobile Station's M1 request, the
Authentication Server prepares an M2 package containing:

- Protocol and server identity
- Session and attempt identifiers
- Mobile Station pseudonym binding
- Fresh Authentication Server nonce
- Ephemeral ML-KEM public-key package
- Encrypted quantum control schedule
- Issue and expiration timestamps
- Optional transcript binding
- ML-DSA signing-key information

The complete unsigned package is serialized canonically and signed using
the Authentication Server's long-term ML-DSA private key.

The Mobile Station must verify the ML-DSA signature before using the
ML-KEM public key or encrypted control schedule.
"""

