"""
FT-QuPAP Gaussian Process Model Loader

This module loads and validates the trained FT-QuPAP Gaussian Process
attack-detection artifacts.

Supported artifact layouts
==========================

1. Final project structure:

    models/
        gp_model.pkl
        feature_scaler.pkl
        calibration_model.pkl
        threshold.json
        feature_order.json
        model_metadata.json

2. Notebook-compatible combined bundle:

    models/
        ft_qupap_gp_detector.joblib

Notebook bundle format:

    {
        "model": trained_gp_pipeline,
        "calibrator": optional_isotonic_calibrator,
        "feature_columns": FEATURE_COLUMNS,
        "protocol_version": "...",
        "seed": 20260701,
        "raw_calibration_gp_attack_threshold": 0.09,
        "gp_attack_threshold": 0.15,
        "training_source": "...",
        "calibration_method": "isotonic_regression",
        "session_gp_data_mode": "large",
        "session_gp_split_sizes": {...},
    }

Security warning
================

Joblib and pickle artifacts can execute Python code while loading.
Only load model artifacts generated by this trusted FT-QuPAP project.
Never load an untrusted model file received from another person or
downloaded from an unknown source.
"""

